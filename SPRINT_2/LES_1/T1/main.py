battery = 15  # Test ook met 20 en 80

# Groter dan 20
if battery > 20:
    print("Batterij is hoger dan 20%")

# Kleiner dan 20
if battery < 20:
    print("Batterij is lager dan 20%")

# Groter dan of gelijk aan 20
if battery >= 20:
    print("Batterij is minimaal 20%")

# Kleiner dan of gelijk aan 20
if battery <= 20:
    print("Batterij is maximaal 20%")

# Gelijk aan 20
if battery == 20:
    print("Batterij is precies 20%")

# Ongelijk aan 20
if battery != 20:
    print("Batterij is niet gelijk aan 20%")